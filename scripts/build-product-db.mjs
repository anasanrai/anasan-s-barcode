/**
 * build-product-db.mjs
 * Merges product CSV files, deduplicates by sku_id,
 * extracts all associated barcodes (including secondary/multi barcodes),
 * and writes client/src/data/products.ts
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const CSV_FILES = [
  "product-list-2026-09-02-3434237f-735d-47b9-9e72-f80cd11f8a2c.csv",
  "product-list-2026-09-02-2aa27cc8-4270-4cb8-babc-500ce1eb4c42.csv",
];

const outDir = join(root, "client", "src", "data");
const targetTsFile = join(outDir, "products.ts");

const existingCsvs = CSV_FILES.map((f) => join(root, f)).filter((p) => existsSync(p));

if (existingCsvs.length === 0) {
  if (existsSync(targetTsFile)) {
    console.log(`[build-product-db] CSV files not found in build environment. Using pre-built ${targetTsFile}`);
    process.exit(0);
  } else {
    console.error(`[build-product-db] Error: No CSV files found and ${targetTsFile} does not exist!`);
    process.exit(1);
  }
}

/**
 * Parse a CSV line respecting quoted fields that may contain commas.
 */
function parseCsvLine(line) {
  const result = [];
  let field = "";
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      inQuotes = !inQuotes;
    } else if (ch === "," && !inQuotes) {
      result.push(field);
      field = "";
    } else {
      field += ch;
    }
  }
  result.push(field);
  return result;
}

/**
 * Extract all clean barcodes from a comma-separated barcode string.
 */
function parseBarcodes(raw) {
  if (!raw) return [];
  const cleaned = raw.replace(/["\r\n]/g, "").trim();
  const parts = cleaned.split(",").map((s) => s.trim()).filter(Boolean);
  const valid = [];
  for (const part of parts) {
    const digits = part.replace(/\D/g, "");
    if (digits.length >= 6 && !valid.includes(digits)) {
      valid.push(digits);
    }
  }
  return valid;
}

const seen = new Map(); // sku_id → product record

for (const filename of CSV_FILES) {
  const filepath = join(root, filename);
  const lines = readFileSync(filepath, "utf8").split("\n");
  const headers = parseCsvLine(lines[0]);

  const idx = {
    sku: headers.indexOf("sku_id"),
    name: headers.indexOf("product_name"),
    barcode: headers.indexOf("barcodes"),
    category: headers.indexOf("parent_category"),
    subcategory: headers.indexOf("category"),
    deleted: headers.indexOf("is_deleted"),
  };

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    const cols = parseCsvLine(line);
    const sku = cols[idx.sku]?.trim();
    if (!sku || sku === "sku_id") continue; // skip header repeat

    const barcodes = parseBarcodes(cols[idx.barcode]);
    if (barcodes.length === 0) continue; // skip entries with no barcode

    const name = cols[idx.name]?.trim() ?? "";
    if (!name) continue;

    const parentCat = cols[idx.category]?.trim() ?? "";
    const subCat = cols[idx.subcategory]?.trim() ?? "";
    const isEvd =
      sku.toUpperCase().startsWith("EVD") ||
      parentCat === "Everyday Roastery" ||
      parentCat.toLowerCase().includes("coffee");

    const existing = seen.get(sku);
    if (!existing) {
      seen.set(sku, {
        sku,
        name,
        barcode: barcodes[0],
        barcodes,
        category: parentCat,
        subcategory: subCat,
        isEvd,
      });
    } else {
      // Merge any new barcodes discovered in secondary dark store file
      for (const b of barcodes) {
        if (!existing.barcodes.includes(b)) {
          existing.barcodes.push(b);
        }
      }
    }
  }
}

const products = Array.from(seen.values()).sort((a, b) =>
  a.sku.localeCompare(b.sku),
);

const evdCount = products.filter((p) => p.isEvd).length;
console.log(`[build-product-db] Total unique active products: ${products.length}`);
console.log(`[build-product-db] Total EVD Coffee products: ${evdCount}`);

mkdirSync(outDir, { recursive: true });

const ts = `// AUTO-GENERATED by scripts/build-product-db.mjs — do not edit manually
// Last generated: ${new Date().toISOString()}
// Products: ${products.length} | EVD: ${evdCount}

export interface Product {
  sku: string;
  name: string;
  barcode: string;
  barcodes?: string[];
  category: string;
  subcategory: string;
  isEvd: boolean;
}

export const PRODUCTS: Product[] = ${JSON.stringify(products, null, 2)};

export const EVD_PRODUCTS: Product[] = PRODUCTS.filter((p) => p.isEvd);
`;

writeFileSync(join(outDir, "products.ts"), ts, "utf8");
console.log(`[build-product-db] Written: ${targetTsFile}`);
